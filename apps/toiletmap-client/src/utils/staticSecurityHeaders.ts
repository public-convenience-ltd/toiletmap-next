/**
 * The security headers for static assets, as Cloudflare `_headers` rules. Static assets
 * (prerendered pages, /cms, /_astro/*, images) are served without running the worker, so
 * src/middleware.ts never sees them; the build writes these rules into dist/client/_headers
 * instead (src/integrations/securityHeaders.ts). Same values as the middleware's, from
 * src/utils/securityHeaders.ts.
 *
 * How Cloudflare reads `_headers` (workers-shared): rules are keyed by path, so a second rule
 * for the same path REPLACES the first (hence one generated rule each for /*, /cms and
 * /cms/*, and none of those paths in public/_headers). Every rule matching a request then
 * runs in file order: `! Name` (with the space) removes a header an earlier rule set, and
 * setting a header an earlier rule set appends it with a comma. So the CMS rules come after
 * the catch-all and remove its CSP, COOP and Referrer-Policy before setting their own.
 */
import {
  baseSecurityHeaders,
  CSP_HEADER,
  CSP_REPORT_ONLY_HEADER,
  contentSecurityPolicyFor,
  crossOriginOpenerPolicy,
} from "./securityHeaders";

/** Cloudflare ignores `_headers` lines longer than this. */
export const MAX_HEADERS_LINE_LENGTH = 2000;

export const GENERATED_MARKER =
  "# Security headers (generated by src/integrations/securityHeaders.ts";

export interface StaticHeadersOptions {
  /** A production build (CLOUDFLARE_ENV=production): adds HSTS. */
  production: boolean;
  /** Hashes of the inline scripts the site ships (src/utils/inlineScripts.ts). */
  scriptHashes: readonly string[];
}

function rule(pattern: string, lines: string[]): string {
  return [pattern, ...lines.map((line) => `  ${line}`)].join("\n");
}

/** The catch-all rule: goes before every other rule in `_headers`. */
export function staticCatchAllRule({ production, scriptHashes }: StaticHeadersOptions): string {
  // Static assets are only ever served over HTTPS by Cloudflare.
  const base = baseSecurityHeaders({ pathname: "/", production, https: true });
  const [cspName, csp] = contentSecurityPolicyFor("/", {
    scriptHashes,
    upgradeInsecureRequests: production,
  });
  return rule("/*", [
    ...Object.entries(base).map(([name, value]) => `${name}: ${value}`),
    `${cspName}: ${csp}`,
  ]);
}

/** Paths the generated rules own: public/_headers must not have rules for them. */
export const GENERATED_PATHS = ["/*", "/cms", "/cms/*"] as const;

/**
 * The /cms rules (Sveltia CMS, public/cms/): its own CSP and COOP, kept out of search results,
 * and no referrer to other sites. They go after the catch-all.
 */
export function staticCmsRules(): string {
  const [cspName, csp] = contentSecurityPolicyFor("/cms/", {});
  const coop = crossOriginOpenerPolicy("/cms/");
  const lines = [
    "X-Robots-Tag: noindex, nofollow",
    `! ${CSP_HEADER}`,
    `! ${CSP_REPORT_ONLY_HEADER}`,
    "! Cross-Origin-Opener-Policy",
    "! Referrer-Policy",
    `${cspName}: ${csp}`,
    ...(coop ? [`Cross-Origin-Opener-Policy: ${coop}`] : []),
    "Referrer-Policy: same-origin",
  ];
  return [rule("/cms", lines), rule("/cms/*", lines)].join("\n");
}

/**
 * `existing` (public/_headers as copied into the build) with the generated rules added: the
 * catch-all first, the CMS overrides last. Throws if a line is too long for Cloudflare, so a
 * build never ships headers that are silently dropped. Running it twice changes nothing.
 */
export function withStaticSecurityHeaders(existing: string, options: StaticHeadersOptions): string {
  if (existing.includes(GENERATED_MARKER)) return existing;
  for (const line of existing.split("\n")) {
    const path = line.trim();
    if (!/^\s/.test(line) && (GENERATED_PATHS as readonly string[]).includes(path)) {
      throw new Error(
        `public/_headers has a rule for ${path}, which the generated security headers own (a second rule for a path replaces the first): add its headers in src/utils/staticSecurityHeaders.ts instead.`,
      );
    }
  }
  const header = `${GENERATED_MARKER}; values from src/utils/securityHeaders.ts)`;
  const content = [
    header,
    staticCatchAllRule(options),
    "",
    existing.trim(),
    "",
    "# /cms (generated; must stay after the catch-all rule)",
    staticCmsRules(),
    "",
  ].join("\n");
  for (const line of content.split("\n")) {
    if (line.length > MAX_HEADERS_LINE_LENGTH) {
      throw new Error(
        `_headers line is ${line.length} characters (Cloudflare's limit is ${MAX_HEADERS_LINE_LENGTH}): ${line.slice(0, 80)}…`,
      );
    }
  }
  return content;
}
